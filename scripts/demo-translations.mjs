export function bilingual(value, key = '') {
  if (typeof value === 'string')
    return fields.has(key) && translations[value]
      ? { values: { 'en-US': value, ar: translations[value] } }
      : value
  if (Array.isArray(value)) return value.map((item) => bilingual(item, key))
  if (!value || typeof value !== 'object' || ('values' in value && Object.keys(value).length === 1))
    return value
  return Object.fromEntries(
    Object.entries(value).map(([field, item]) => [field, bilingual(item, field)]),
  )
}
